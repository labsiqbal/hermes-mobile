import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { unlinkSync } from 'node:fs';
const outfile=join(tmpdir(),`session-activity-${process.pid}.mjs`);
buildSync({entryPoints:['src/lib/session-activity.ts'],outfile,bundle:true,platform:'node',format:'esm'});
const {activityKey,getActivity,recordActivity,readActivity}=await import(pathToFileURL(outfile));
const key=activityKey('gateway','https://fictional.invalid','session');
const emit=(type,payload={})=>recordActivity(key,{type,payload,session_id:'session'});
emit('message.start');assert.equal(getActivity(key).running,true);
emit('subagent.start',{subagent_id:'child',goal:'Check fictional fixture'});
emit('subagent.tool',{subagent_id:'child',tool_name:'terminal',text:'Fixture check'});
emit('message.complete');assert.equal(getActivity(key).children[0].status,'running');
emit('subagent.complete',{subagent_id:'child',status:'completed',summary:'Fixture passed'});
assert.equal(getActivity(key).unread,true);assert.equal(getActivity(key).children[0].status,'completed');
assert.match(getActivity(key).children[0].log.join('\n'),/Fixture check/);
readActivity(key);assert.equal(getActivity(key).unread,false);
emit('message.start');emit('error');assert.equal(getActivity(key).failed,true);assert.equal(getActivity(key).unread,false);
emit('message.start');emit('message.complete',{status:'error'});assert.equal(getActivity(key).failed,true);
assert.equal(getActivity(activityKey('gateway','https://other.invalid','session')).failed,false);
const before=getActivity(key);emit('subagent.tool',{subagent_id:42});assert.equal(getActivity(key),before);
unlinkSync(outfile);
console.log('Session activity: processing, child logs, unread/read, errors, scope and malformed payload checks passed.');
